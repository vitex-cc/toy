// Generate the static Chinese TTS clips used by the app.
//
// Collects every phrase from the message tables, keeps clips that already
// exist in src/generated/tts-audio.js, and synthesizes only the missing ones
// with Volcengine TTS. Credentials come from the environment and are never
// written into the repo:
//
//   VOLC_TTS_APP_ID=xxx VOLC_TTS_ACCESS_KEY=xxx npm run gen:tts
//
// Optional: VOLC_TTS_VOICE, VOLC_TTS_RESOURCE_ID (defaults match the voice the
// existing clips were made with).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MASCOT_MESSAGES } from "../src/composables/question.js";
import { LETTER_MESSAGES } from "../src/composables/letters.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/generated/tts-audio.js");
const ENDPOINT = "https://openspeech.bytedance.com/api/v3/tts/unidirectional";
const VOICE = process.env.VOLC_TTS_VOICE || "zh_female_sajiaonvyou_moon_bigtts";
const RESOURCE = process.env.VOLC_TTS_RESOURCE_ID || "seed-tts-1.0";

function readExisting() {
  if (!fs.existsSync(OUT)) return {};
  const src = fs.readFileSync(OUT, "utf8");
  const map = {};
  for (const m of src.matchAll(/^ {2}("(?:[^"\\]|\\.)*"): "(data:audio\/mpeg;base64,[^"]+)"/gm)) {
    map[JSON.parse(m[1])] = m[2];
  }
  return map;
}

async function synthesize(text) {
  const appId = process.env.VOLC_TTS_APP_ID;
  const key = process.env.VOLC_TTS_ACCESS_KEY;
  if (!appId || !key) {
    throw new Error("missing VOLC_TTS_APP_ID / VOLC_TTS_ACCESS_KEY");
  }
  const res = await fetch(ENDPOINT, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Api-App-Id": appId,
      "X-Api-Access-Key": key,
      "X-Api-Resource-Id": RESOURCE,
    },
    body: JSON.stringify({
      user: { uid: "learn-app" },
      req_params: {
        text,
        speaker: VOICE,
        audio_params: { format: "mp3", sample_rate: 24000 },
      },
    }),
  });
  if (!res.ok) throw new Error(`TTS HTTP ${res.status}: ${await res.text()}`);
  // Response is newline-delimited JSON; `data` holds base64 audio chunks.
  let b64 = "";
  for (const line of (await res.text()).split("\n")) {
    if (!line.trim()) continue;
    const j = JSON.parse(line);
    if (j.code && j.code !== 0 && j.code !== 20000000) {
      throw new Error(`TTS error ${j.code}: ${j.message}`);
    }
    if (j.data) b64 += j.data;
  }
  if (!b64) throw new Error(`TTS returned no audio for: ${text}`);
  return Buffer.from(b64, "base64").toString("base64");
}

const phrases = [
  ...new Set([
    ...Object.values(MASCOT_MESSAGES).flat(),
    ...Object.values(LETTER_MESSAGES).flat(),
  ]),
];
const existing = readExisting();
const result = {};
let created = 0;

for (const text of phrases) {
  if (existing[text]) {
    result[text] = existing[text];
    continue;
  }
  console.log(`synthesizing: ${text}`);
  result[text] = `data:audio/mpeg;base64,${await synthesize(text)}`;
  created += 1;
}

const unused = Object.keys(existing).filter((t) => !(t in result));
if (unused.length) console.warn(`dropping unused clips: ${unused.join(" / ")}`);

const body = Object.entries(result)
  .map(([k, v]) => `  ${JSON.stringify(k)}: "${v}"`)
  .join(",\n");
fs.writeFileSync(
  OUT,
  `// Static TTS audio data embedded as base64 data URLs.\n// Generated by scripts/gen-tts.js — do not edit by hand.\n\nexport const STATIC_TTS_AUDIO = {\n${body}\n};\n`,
);
console.log(`done: ${phrases.length} phrases, ${created} newly synthesized`);
